-- The ledger of what went to a CRM (2026-10-13): one row per result per
-- connection, so nothing is pushed twice, and a failure is retried a few
-- times and then left visible. external_* are the CRM's own ids.
CREATE TABLE IF NOT EXISTS public.crm_push (
	push_id             bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
	account_id          bigint NOT NULL,
	connection_id       bigint NOT NULL,
	plan_id             bigint NOT NULL,
	-- 'prospect' | 'artifact', and that row's id.
	row_kind            varchar(12) NOT NULL,
	row_id              bigint NOT NULL,
	-- 'created' | 'matched' (already in the CRM, by email) | 'failed'
	status              varchar(12) NOT NULL,
	external_person_id  text NOT NULL DEFAULT '',
	external_org_id     text NOT NULL DEFAULT '',
	external_lead_id    text NOT NULL DEFAULT '',
	error               text NOT NULL DEFAULT '',
	attempts            integer NOT NULL DEFAULT 1,
	updated_at          timestamptz NOT NULL DEFAULT now(),
	PRIMARY KEY (push_id),
	UNIQUE (connection_id, row_kind, row_id),
	FOREIGN KEY (connection_id) REFERENCES public.crm_connection(connection_id) ON DELETE CASCADE,
	FOREIGN KEY (plan_id) REFERENCES public.plan(plan_id) ON DELETE CASCADE
);
CREATE INDEX IF NOT EXISTS crm_push_plan_idx ON public.crm_push (plan_id, connection_id, status);
