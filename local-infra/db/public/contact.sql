-- The built-in CRM's people (2026-10-18; the `crm` module, store::MODULES).
-- A person a workspace keeps track of: brought in from a search plan's results
-- or typed in by hand. Not to be confused with crm_connection & co., which push
-- results out to someone else's CRM.
CREATE TABLE IF NOT EXISTS public.contact (
	contact_id     bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
	account_id     bigint NOT NULL REFERENCES public.account(account_id) ON DELETE CASCADE,
	name           varchar(255) NOT NULL DEFAULT '',
	email          varchar(320) NOT NULL DEFAULT '',
	phone          varchar(100) NOT NULL DEFAULT '',
	title          varchar(255) NOT NULL DEFAULT '',
	company        varchar(255) NOT NULL DEFAULT '',
	website        text NOT NULL DEFAULT '',
	linkedin       text NOT NULL DEFAULT '',
	location       varchar(255) NOT NULL DEFAULT '',
	-- What the workspace knows about them, edited by people. Scraped facts a
	-- result had beyond the fields above go here on import.
	notes          text NOT NULL DEFAULT '',
	-- lead | contacted | qualified | customer | lost — store::CONTACT_STAGES.
	-- A fixed list on purpose: this is the simple CRM.
	stage          varchar(16) NOT NULL DEFAULT 'lead',
	-- When to get back to them; the list sorts and flags on it.
	follow_up_on   date,
	-- The newest logged activity's time, kept here so the list need not join.
	last_touch_at  timestamptz,
	-- Where it came from: 'manual', or the result it was imported from
	-- ('prospect' | 'artifact' + its id). The pair is what makes importing the
	-- same plan twice add nothing. The plan may be deleted later; the contact stays.
	source_kind    varchar(16) NOT NULL DEFAULT 'manual',
	source_id      bigint,
	plan_id        bigint REFERENCES public.plan(plan_id) ON DELETE SET NULL,
	-- The plan's name when it was imported, so it still reads after a delete.
	source_plan    varchar(255) NOT NULL DEFAULT '',
	created_by     bigint,
	created_at     timestamptz NOT NULL DEFAULT now(),
	updated_at     timestamptz NOT NULL DEFAULT now(),
	PRIMARY KEY (contact_id)
);
CREATE INDEX IF NOT EXISTS contact_account_idx ON public.contact (account_id, updated_at DESC);
CREATE UNIQUE INDEX IF NOT EXISTS contact_source_idx
    ON public.contact (account_id, source_kind, source_id) WHERE source_id IS NOT NULL;
-- Import links a result to someone already here by address rather than adding a twin.
CREATE INDEX IF NOT EXISTS contact_email_idx ON public.contact (account_id, lower(email)) WHERE email <> '';
