-- The built-in CRM's communications log: one row per thing that happened with
-- a contact — an email sent, a call, a meeting, a LinkedIn message, or a note.
-- Logged by people; Huntwell sends nothing (see Outreach).
CREATE TABLE IF NOT EXISTS public.contact_activity (
	activity_id    bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
	account_id     bigint NOT NULL REFERENCES public.account(account_id) ON DELETE CASCADE,
	contact_id     bigint NOT NULL REFERENCES public.contact(contact_id) ON DELETE CASCADE,
	-- note | email | call | meeting | linkedin | reddit — store::ACTIVITY_KINDS.
	kind           varchar(16) NOT NULL DEFAULT 'note',
	body           text NOT NULL DEFAULT '',
	-- When it happened, which is not always when it was written down.
	occurred_at    timestamptz NOT NULL DEFAULT now(),
	created_by     bigint,
	created_at     timestamptz NOT NULL DEFAULT now(),
	PRIMARY KEY (activity_id)
);
CREATE INDEX IF NOT EXISTS contact_activity_contact_idx ON public.contact_activity (contact_id, occurred_at DESC);
