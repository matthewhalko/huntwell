-- One message in a support chat, from the customer or an operator.
-- The customer's text is theirs, unvetted: escaped wherever it is shown.
CREATE TABLE IF NOT EXISTS public.support_message (
	message_id      bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
	conversation_id bigint NOT NULL REFERENCES public.support_conversation (conversation_id) ON DELETE CASCADE,
	-- 'customer' | 'operator'
	author          varchar(8)   NOT NULL,
	-- Which operator answered, for the record; never shown to the customer.
	operator_email  varchar(320) NOT NULL DEFAULT '',
	body            text         NOT NULL,
	created_at      timestamptz  NOT NULL DEFAULT now(),
	PRIMARY KEY (message_id)
);
CREATE INDEX IF NOT EXISTS support_message_thread_idx ON public.support_message (conversation_id, message_id);
-- The message's ts in the chat's Slack thread: set when it was posted there,
-- or when it came from there (an operator replying in Slack). Empty = still
-- owed to the thread. Unique per chat, so Slack delivering the same reply
-- twice records it once.
ALTER TABLE public.support_message ADD COLUMN IF NOT EXISTS slack_ts varchar(32) NOT NULL DEFAULT '';
CREATE UNIQUE INDEX IF NOT EXISTS support_message_slack_idx ON public.support_message (conversation_id, slack_ts) WHERE slack_ts <> '';
