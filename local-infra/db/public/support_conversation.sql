-- A support chat: someone on the public site or in the app asking for help,
-- and an operator answering from admin → Support.
--
-- Not a tenant table, like `waitlist`: a visitor has no account, and only the
-- admin reads across it. A signed-in person's chat records who they are
-- (`account_id`) and the workspace they were in (`workspace_id`), so the
-- operator sees the context without asking; both are cleared by
-- `store::purge_account` with the account.
CREATE TABLE IF NOT EXISTS public.support_conversation (
	conversation_id   bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
	account_id        bigint,
	workspace_id      bigint,
	-- Where a reply is emailed when they are no longer on the page. A
	-- signed-in person's account address; a visitor's own, as typed.
	email             varchar(320) NOT NULL,
	name              varchar(80)  NOT NULL DEFAULT '',
	-- A visitor's way back into their chat: the widget keeps the token, the
	-- row keeps its SHA-256 for lookup and a sealed copy (signing::seal_secret)
	-- so a reply email can carry the same link. Signed-in chats have neither:
	-- the session is the way in.
	token_hash        text,
	token_sealed      text NOT NULL DEFAULT '',
	-- 'open' | 'closed'. A message on a closed chat opens it again.
	status            varchar(8)   NOT NULL DEFAULT 'open',
	-- The page they started from, for context ("on /pricing").
	page              varchar(300) NOT NULL DEFAULT '',
	ip                varchar(64)  NOT NULL DEFAULT '',
	created_at        timestamptz  NOT NULL DEFAULT now(),
	last_message_at   timestamptz  NOT NULL DEFAULT now(),
	-- When each side last looked: what is unread for the other.
	customer_seen_at  timestamptz,
	operator_seen_at  timestamptz,
	closed_at         timestamptz,
	closed_by         varchar(320) NOT NULL DEFAULT '',
	-- The Slack post owed for this chat ('new' | 'reopened'), sent by the
	-- notification service with the mail backoff. NULL due = nothing owed.
	slack_due_at      timestamptz,
	slack_reason      varchar(12)  NOT NULL DEFAULT '',
	slack_attempts    integer      NOT NULL DEFAULT 0,
	slack_error       text         NOT NULL DEFAULT '',
	PRIMARY KEY (conversation_id)
);
CREATE UNIQUE INDEX IF NOT EXISTS support_conversation_token_idx ON public.support_conversation (token_hash) WHERE token_hash IS NOT NULL;
CREATE INDEX IF NOT EXISTS support_conversation_inbox_idx ON public.support_conversation (status, last_message_at DESC);
CREATE INDEX IF NOT EXISTS support_conversation_account_idx ON public.support_conversation (account_id, last_message_at DESC) WHERE account_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS support_conversation_slack_idx ON public.support_conversation (slack_due_at) WHERE slack_due_at IS NOT NULL;
-- The chat's thread in the operators' Slack channel (`support::slack`): the
-- channel and the parent post's ts. Replies in that thread are the operator
-- answering; empty until the first post.
ALTER TABLE public.support_conversation ADD COLUMN IF NOT EXISTS slack_channel   varchar(32) NOT NULL DEFAULT '';
ALTER TABLE public.support_conversation ADD COLUMN IF NOT EXISTS slack_thread_ts varchar(32) NOT NULL DEFAULT '';
CREATE INDEX IF NOT EXISTS support_conversation_thread_idx ON public.support_conversation (slack_channel, slack_thread_ts) WHERE slack_thread_ts <> '';
