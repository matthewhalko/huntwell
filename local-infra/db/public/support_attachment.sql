-- An image on a support message: a screenshot the person pasted, attached or
-- snapped from the page, or one an operator posted in the chat's Slack thread.
-- Kept in the database beside the message (a chat line's worth: at most four
-- per message, 4 MB each, scaled down in the browser first), so a chat and
-- everything in it go together when the chat is deleted.
--
-- `content_type` is decided from the bytes (`store::support_image_type`),
-- never from what the browser or Slack said the file was.
CREATE TABLE IF NOT EXISTS public.support_attachment (
	attachment_id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
	message_id    bigint NOT NULL REFERENCES public.support_message (message_id) ON DELETE CASCADE,
	content_type  varchar(32) NOT NULL,
	bytes         bytea       NOT NULL,
	created_at    timestamptz NOT NULL DEFAULT now(),
	PRIMARY KEY (attachment_id)
);
CREATE INDEX IF NOT EXISTS support_attachment_message_idx ON public.support_attachment (message_id, attachment_id);
