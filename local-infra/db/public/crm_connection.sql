-- A CRM a workspace connected, to push search results into (2026-10-13).
-- Pipedrive first; `provider` names the adapter in cmd/src/crm/, so another
-- CRM is another adapter, not another table.
--
-- credential is the API token: sealed (web::signing::seal_secret), never sent
-- to a browser, opened only by the website's sync loop.
CREATE TABLE IF NOT EXISTS public.crm_connection (
	connection_id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
	account_id    bigint NOT NULL,
	-- 'pipedrive'
	provider      varchar(24) NOT NULL,
	-- What the person sees: the CRM account's name, e.g. "Acme (acme.pipedrive.com)".
	label         varchar(200) NOT NULL DEFAULT '',
	credential    text NOT NULL,
	-- Provider settings: Pipedrive's company_domain; create_lead.
	settings_json text NOT NULL DEFAULT '{}',
	created_by    bigint,
	created_at    timestamptz NOT NULL DEFAULT now(),
	-- A credential the CRM refused: pushing stops until it is reconnected.
	paused        boolean NOT NULL DEFAULT false,
	last_error    text NOT NULL DEFAULT '',
	last_ok_at    timestamptz,
	PRIMARY KEY (connection_id),
	FOREIGN KEY (account_id) REFERENCES public.account(account_id) ON DELETE CASCADE
);
CREATE INDEX IF NOT EXISTS crm_connection_account_idx ON public.crm_connection (account_id);
